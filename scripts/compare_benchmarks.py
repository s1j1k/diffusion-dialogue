"""Rebuild benchmarks/README.md: every model version's responses to the same prompts.

    python scripts/compare_benchmarks.py
"""
import glob
import json
import os

ROOT = os.path.join(os.path.dirname(__file__), "..")
BENCH = os.path.join(ROOT, "benchmarks")


def main():
    prompts = [json.loads(line) for line in open(os.path.join(BENCH, "prompts.jsonl"), encoding="utf-8")]
    registry = json.load(open(os.path.join(ROOT, "models", "registry.json"), encoding="utf-8"))
    reg = {m["version"]: m for m in registry["models"]}
    results = [json.load(open(p, encoding="utf-8")) for p in glob.glob(os.path.join(BENCH, "results", "*.json"))]
    order = {m["version"]: i for i, m in enumerate(registry["models"])}
    results.sort(key=lambda r: order.get(r["version"], 999))

    L = ["# Benchmark: model versions on fixed prompts", "",
         "Every model version answers the same prompts (`prompts.jsonl`) with fixed seeds, so outputs",
         "can be compared across versions. Full outputs, settings and metadata are in `results/`;",
         "model details and how to rebuild each version are in `../models/`.",
         "Generated by `scripts/compare_benchmarks.py`.", "",
         "## Versions", "",
         "| Version | Date | Model | Training | Headline setting | Test sentence BLEU | Test distinct-2 |",
         "| --- | --- | --- | --- | --- | --- | --- |"]
    for r in results:
        m = reg.get(r["version"], {})
        best = max(r.get("test_metrics") or [{}], key=lambda x: x.get("sentence_bleu", -1))
        bleu = f"{best['sentence_bleu']:.4f}" if "sentence_bleu" in best else "n/a"
        d2 = f"{best['distinct_2']:.3f}" if "distinct_2" in best else "n/a"
        L.append(f"| {r['version']} | {m.get('date', '')} | {m.get('model_summary', '')} | "
                 f"{m.get('training_summary', '')} | {r['settings'][0]['label'] if r.get('settings') else 'n/a'} | "
                 f"{bleu} | {d2} |")
    L += [""]

    L += ["## Responses", "",
          "First seed, headline setting of each version. Other seeds and settings are in `results/`.", ""]
    for pr in prompts:
        L += [f"### `{pr['id']}`", "", f"> {pr['prompt']}", ""]
        if pr.get("reference"):
            L += [f"*Reference reply:* {pr['reference']}", ""]
        rows = []
        for r in results:
            setting = r["settings"][0]["label"] if r.get("settings") else None
            hit = next((o for o in r["outputs"] if o["id"] == pr["id"] and o["setting"] == setting), None)
            if hit:
                rows.append(f"| {r['version']} | {hit['responses'][0].replace('|', '/')} |")
        if rows:
            L += ["| Version | Response |", "| --- | --- |", *rows, ""]
        else:
            L += ["*(no responses recorded)*", ""]

    with open(os.path.join(BENCH, "README.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("wrote benchmarks/README.md")


if __name__ == "__main__":
    main()
